// Category names mapped to icons. Covers the current defaults (DefaultCategories.java) and some
// older ones that existing workspaces may still have. Subcategories are not listed: they use
// their parent's icon. Custom categories get Tag.
const BY_NAME: Record<string, LucideIcon> = {
  Food: Utensils,
  Transport: Car,
  Housing: House,
  "Bills & Recharges": Receipt,
  Shopping: ShoppingBag,
  Health: HeartPulse,
  Education: GraduationCap,
  Entertainment: Clapperboard,
  Subscriptions: Repeat,
  Travel: Plane,
  "Personal Care": Sparkles,
  "Gifts & Donations": Gift,
  "Fees & Charges": Landmark,
  "Money Lent": HandCoins,
  "Loan Repayment": HandCoins,
  Other: CircleEllipsis,
  Salary: Briefcase,
  Stipend: GraduationCap,
  "Business Income": Store,
  Refunds: Undo2,
  Interest: Percent,
  "Gifts Received": Gift,
  "Money Borrowed": HandCoins,
  "Repayment Received": HandCoins,
  "Other Income": Banknote,
  Labour: Hammer,
  Materials: Package,
  "Contractor Payments": HardHat,
  "Broker Commission": Handshake,
  "Registration & Legal": Scale,
  "Office & Admin": Building2,
  "Sale Proceeds": Banknote,
  "Advance Received": Banknote,
  "Rent Received": House,
  Commission: Handshake,
};

/** The icon for a category: its own, else its parent's, else a generic tag. */
export function categoryIcon(
  category: { name: string; parent_id?: string } | undefined,
  parent: { name: string } | undefined,
): LucideIcon {
  if (!category) return Tag;
  return BY_NAME[category.name] ?? (parent ? BY_NAME[parent.name] : undefined) ?? Tag;
}
